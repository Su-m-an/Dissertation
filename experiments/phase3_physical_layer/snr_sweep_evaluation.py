"""
snr_sweep_evaluation.py

Evaluates all six models across the rho_E (eavesdropper SNR) sweep
generated by generate_sweep_data.sh. rho_E is the physical-layer
parameter that directly controls how strong the eavesdropper's spoofed
signal is relative to noise -- low rho_E means the attack is nearly
buried in noise (hard detection problem), high rho_E means an obviously
strong interferer (easy). rho_E=5 (with rho_u=5) is the setting that
produced the existing baseline data.

Architecture/hyperparameters are fixed to the Phase 1 tuned values for
every model (only the training/test data changes across the sweep, not
the search) -- consistent with how class_imbalance_stress_test.py
(Phase 2) was designed, for the same reason: this experiment isolates
the effect of physical-layer difficulty, not a re-run of hyperparameter
search at every difficulty level.

Writes results/snr_sweep_results.csv incrementally, one (rho_E, model)
row at a time, and skips combinations already present on disk. TC-SVM at
full scale (184,000 rows, predict_proba included) is the slow part of
this sweep -- a single earlier run lost ~66 minutes of progress to an
interruption because results were only written at the very end; this
version survives that.
"""

import json
import glob
import os

import numpy as np
import pandas as pd
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

from sklearn.model_selection import train_test_split
from sklearn.preprocessing import StandardScaler
from sklearn.svm import SVC
from sklearn.ensemble import RandomForestClassifier
from xgboost import XGBClassifier
from sklearn.metrics import accuracy_score, precision_score, recall_score, f1_score, roc_auc_score

import torch
import torch.nn as nn
from torch.utils.data import TensorDataset, DataLoader

SEED = 42
P1 = "experiments/phase1_statistical_rigor/results"
OUT = "experiments/phase3_physical_layer"
RESULTS_CSV = f"{OUT}/results/snr_sweep_results.csv"
COLUMNS = ["rho_E", "model", "accuracy", "precision", "recall", "f1", "auc"]

torch.manual_seed(SEED)
np.random.seed(SEED)


def load_best_params(tag):
    with open(f"{P1}/{tag}_best_params.json") as f:
        return json.load(f)


def discover_sweep_points():
    dirs = sorted(glob.glob(f"{OUT}/raw_sweep/rho_E_*"),
                   key=lambda d: float(d.split("rho_E_")[1]))
    return [(float(d.split("rho_E_")[1]), d) for d in dirs]


def eval_metrics(y_true, y_pred, y_prob):
    return {
        "accuracy": accuracy_score(y_true, y_pred),
        "precision": precision_score(y_true, y_pred, zero_division=0),
        "recall": recall_score(y_true, y_pred, zero_division=0),
        "f1": f1_score(y_true, y_pred, zero_division=0),
        "auc": roc_auc_score(y_true, y_prob) if len(set(y_true)) > 1 else float("nan"),
    }


def load_done():
    if not os.path.exists(RESULTS_CSV):
        return set()
    df = pd.read_csv(RESULTS_CSV)
    return set(zip(df["rho_E"], df["model"]))


def append_result(row):
    write_header = not os.path.exists(RESULTS_CSV)
    pd.DataFrame([row])[COLUMNS].to_csv(RESULTS_CSV, mode="a", header=write_header, index=False)


# ------------------------------------------------------- classical ---

def classical_factory(tag):
    p = load_best_params(tag)
    if tag == "tc_svm":
        return lambda: SVC(kernel="rbf", probability=True, random_state=SEED, **p)
    if tag == "random_forest":
        return lambda: RandomForestClassifier(random_state=SEED, n_jobs=-1, **p)
    if tag == "xgboost":
        return lambda: XGBClassifier(random_state=SEED, eval_metric="logloss", **p)


def run_classical_point(rho_E, d, done):
    needed = [tag for tag in ["tc_svm", "random_forest", "xgboost"] if (rho_E, tag) not in done]
    if not needed:
        print(f"  SKIP (already done) rho_E={rho_E} tc_svm/random_forest/xgboost")
        return

    data = pd.read_csv(f"{d}/ATD_features.csv")
    X = data[["MEAN", "RATIO"]].values
    y = data["LABEL"].values
    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.20, random_state=SEED, stratify=y)

    scaler = StandardScaler()
    X_train_s = scaler.fit_transform(X_train)
    X_test_s = scaler.transform(X_test)

    for tag in needed:
        model = classical_factory(tag)()
        model.fit(X_train_s, y_train)
        pred = model.predict(X_test_s)
        prob = model.predict_proba(X_test_s)[:, 1]
        m = eval_metrics(y_test, pred, prob)
        m.update({"model": tag, "rho_E": rho_E})
        append_result(m)
        print(f"  rho_E={rho_E:>5} {tag:15s} acc={m['accuracy']:.4f} f1={m['f1']:.4f} auc={m['auc']:.4f}  [saved]")


# ---------------------------------------------------------- neural ---

class MLP(nn.Module):
    def __init__(self, hidden):
        super().__init__()
        layers, d = [], 50
        for h in hidden:
            layers += [nn.Linear(d, h), nn.ReLU()]
            d = h
        layers += [nn.Linear(d, 1)]
        self.net = nn.Sequential(*layers)

    def forward(self, x):
        return self.net(x)


class LSTMClassifier(nn.Module):
    def __init__(self, hidden_size, num_layers=2, dropout=0.3):
        super().__init__()
        self.lstm = nn.LSTM(input_size=1, hidden_size=hidden_size, num_layers=num_layers,
                             dropout=dropout, batch_first=True)
        self.dropout = nn.Dropout(dropout)
        self.fc = nn.Linear(hidden_size, 1)

    def forward(self, x):
        _, (hidden, _) = self.lstm(x)
        return self.fc(self.dropout(hidden[-1]))


class Autoencoder(nn.Module):
    def __init__(self, latent):
        super().__init__()
        self.encoder = nn.Sequential(nn.Linear(50, 32), nn.ReLU(), nn.Linear(32, 16), nn.ReLU(), nn.Linear(16, latent))
        self.decoder = nn.Sequential(nn.Linear(latent, 16), nn.ReLU(), nn.Linear(16, 32), nn.ReLU(), nn.Linear(32, 50))

    def forward(self, x):
        return self.decoder(self.encoder(x))


def train_mlp(X, y, hidden, lr, epochs=30):
    loader = DataLoader(TensorDataset(torch.tensor(X), torch.tensor(y).view(-1, 1)), batch_size=32, shuffle=True)
    model = MLP(tuple(hidden))
    criterion = nn.BCEWithLogitsLoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=lr)
    for _ in range(epochs):
        for inputs, labels in loader:
            optimizer.zero_grad()
            loss = criterion(model(inputs), labels)
            loss.backward()
            optimizer.step()
    return model


def train_lstm(X, y, hidden_size, lr, epochs=40):
    loader = DataLoader(TensorDataset(torch.tensor(X).unsqueeze(-1), torch.tensor(y).view(-1, 1)),
                         batch_size=32, shuffle=True)
    model = LSTMClassifier(hidden_size)
    criterion = nn.BCEWithLogitsLoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=lr)
    for _ in range(epochs):
        for inputs, labels in loader:
            optimizer.zero_grad()
            loss = criterion(model(inputs), labels)
            loss.backward()
            optimizer.step()
    return model


def train_autoencoder(X_normal, latent, lr, epochs=40):
    loader = DataLoader(TensorDataset(torch.tensor(X_normal)), batch_size=32, shuffle=True)
    model = Autoencoder(latent)
    criterion = nn.MSELoss()
    optimizer = torch.optim.Adam(model.parameters(), lr=lr)
    for _ in range(epochs):
        for (batch,) in loader:
            optimizer.zero_grad()
            loss = criterion(model(batch), batch)
            loss.backward()
            optimizer.step()
    return model


def run_neural_point(rho_E, d, done, mlp_params, lstm_params, ae_params):
    needed = [tag for tag in ["mlp", "lstm", "autoencoder"] if (rho_E, tag) not in done]
    if not needed:
        print(f"  SKIP (already done) rho_E={rho_E} mlp/lstm/autoencoder")
        return

    dataset = pd.read_csv(f"{d}/ATD_sequence.csv")
    X = dataset.drop("LABEL", axis=1).values.astype(np.float32)
    y = dataset["LABEL"].values.astype(np.float32)
    X_train, X_test, y_train, y_test = train_test_split(X, y, test_size=0.20, random_state=SEED, stratify=y)

    scaler = StandardScaler()
    X_train_s = scaler.fit_transform(X_train).astype(np.float32)
    X_test_s = scaler.transform(X_test).astype(np.float32)

    if "mlp" in needed:
        model = train_mlp(X_train_s, y_train, **mlp_params)
        model.eval()
        with torch.no_grad():
            prob = torch.sigmoid(model(torch.tensor(X_test_s))).numpy().flatten()
        pred = (prob > 0.5).astype(float)
        m = eval_metrics(y_test, pred, prob)
        m.update({"model": "mlp", "rho_E": rho_E})
        append_result(m)
        print(f"  rho_E={rho_E:>5} mlp             acc={m['accuracy']:.4f} f1={m['f1']:.4f} auc={m['auc']:.4f}  [saved]")

    if "lstm" in needed:
        model = train_lstm(X_train_s, y_train, **lstm_params)
        model.eval()
        with torch.no_grad():
            prob = torch.sigmoid(model(torch.tensor(X_test_s).unsqueeze(-1))).numpy().flatten()
        pred = (prob > 0.5).astype(float)
        m = eval_metrics(y_test, pred, prob)
        m.update({"model": "lstm", "rho_E": rho_E})
        append_result(m)
        print(f"  rho_E={rho_E:>5} lstm            acc={m['accuracy']:.4f} f1={m['f1']:.4f} auc={m['auc']:.4f}  [saved]")

    if "autoencoder" in needed:
        X_normal = X_train_s[y_train == 0]
        X_fit, X_calib = train_test_split(X_normal, test_size=0.20, random_state=SEED)
        model = train_autoencoder(X_fit, **ae_params)
        model.eval()
        with torch.no_grad():
            calib_recon = model(torch.tensor(X_calib)).numpy()
            test_recon = model(torch.tensor(X_test_s)).numpy()
        calib_err = np.mean((X_calib - calib_recon) ** 2, axis=1)
        threshold = np.percentile(calib_err, 95)
        test_err = np.mean((X_test_s - test_recon) ** 2, axis=1)
        pred = (test_err > threshold).astype(int)
        m = eval_metrics(y_test, pred, test_err)
        m.update({"model": "autoencoder", "rho_E": rho_E})
        append_result(m)
        print(f"  rho_E={rho_E:>5} autoencoder     acc={m['accuracy']:.4f} f1={m['f1']:.4f} auc={m['auc']:.4f}  [saved]")


def make_figures(df):
    plt.figure(figsize=(10, 7))
    for model_tag in ["tc_svm", "random_forest", "xgboost", "mlp", "lstm", "autoencoder"]:
        sub = df[df["model"] == model_tag].sort_values("rho_E")
        if len(sub):
            plt.plot(sub["rho_E"], sub["accuracy"], marker="o", label=model_tag)
    plt.xscale("log")
    plt.xlabel("rho_E (eavesdropper SNR, log scale)")
    plt.ylabel("Accuracy")
    plt.title("Detection accuracy vs. physical-layer difficulty (rho_u=5 fixed)")
    plt.axvline(5, color="gray", linestyle="--", linewidth=1, label="baseline (rho_E=5)")
    plt.legend()
    plt.grid(True, which="both", alpha=0.3)
    plt.tight_layout()
    plt.savefig(f"{OUT}/figures/snr_sweep_accuracy.png", dpi=300)
    plt.close()

    plt.figure(figsize=(10, 7))
    for model_tag in ["tc_svm", "random_forest", "xgboost", "mlp", "lstm", "autoencoder"]:
        sub = df[df["model"] == model_tag].sort_values("rho_E")
        if len(sub):
            plt.plot(sub["rho_E"], sub["auc"], marker="o", label=model_tag)
    plt.xscale("log")
    plt.xlabel("rho_E (eavesdropper SNR, log scale)")
    plt.ylabel("AUC")
    plt.title("Detection AUC vs. physical-layer difficulty (rho_u=5 fixed)")
    plt.axvline(5, color="gray", linestyle="--", linewidth=1, label="baseline (rho_E=5)")
    plt.legend()
    plt.grid(True, which="both", alpha=0.3)
    plt.tight_layout()
    plt.savefig(f"{OUT}/figures/snr_sweep_auc.png", dpi=300)
    plt.close()


if __name__ == "__main__":
    os.makedirs(f"{OUT}/results", exist_ok=True)
    os.makedirs(f"{OUT}/figures", exist_ok=True)

    sweep_points = discover_sweep_points()
    print(f"Sweep points found: {[p[0] for p in sweep_points]}")

    done = load_done()
    if done:
        print(f"Resuming: {len(done)} (rho_E, model) combinations already on disk, will be skipped.")

    print("\n=== Classical models across rho_E sweep ===")
    for rho_E, d in sweep_points:
        run_classical_point(rho_E, d, done)

    print("\n=== Neural models across rho_E sweep ===")
    mlp_params = load_best_params("mlp")
    lstm_params = load_best_params("lstm")
    ae_params = load_best_params("autoencoder")
    for rho_E, d in sweep_points:
        run_neural_point(rho_E, d, done, mlp_params, lstm_params, ae_params)

    df = pd.read_csv(RESULTS_CSV)
    make_figures(df)

    print(f"\nSaved {RESULTS_CSV}")
    print("Figures: snr_sweep_accuracy.png, snr_sweep_auc.png")
